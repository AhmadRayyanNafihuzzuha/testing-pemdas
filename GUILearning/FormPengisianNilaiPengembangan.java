    private void tombolSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombolSimpanActionPerformed
        // TODO add your handling code here:
        try {
            String nama = namaMahasiswa.getText().trim();
            String nim = nimMahasiswa.getText().trim();
            String prodi = pilihanProdi.getSelectedItem().toString();

            String tugasText = nilaiTugas.getText().trim();
            String utsText = nilaiUTS.getText().trim();
            String uasText = nilaiUAS.getText().trim();

            if (nama.isEmpty() || tugasText.isEmpty()
                || utsText.isEmpty() || uasText.isEmpty()) {

                JOptionPane.showMessageDialog(
                    this, "Semua data harus diisi!"
                );
                return;
            }

            double tugas = Double.parseDouble(tugasText);
            double uts = Double.parseDouble(utsText);
            double uas = Double.parseDouble(uasText);

            if (tugas < 0 || tugas > 100
                || uts < 0 || uts > 100
                || uas < 0 || uas > 100) {

                JOptionPane.showMessageDialog(
                    this, "Nilai harus berada di antara 0 sampai 100!"
                );
                return;
            }

            double rata = (tugas + uts + uas) / 3;

            String grade;
            if (rata >= 90) {
                grade = "A";
            }
            else if (rata >= 80) {
                grade = "B";
            }
            else if (rata >= 70) {
                grade = "C";
            }
            else if (rata >= 60) {
                grade = "D";
            }
            else {
                grade = "E";
            }

            String status = rata >= 75 ? "LULUS" : "TIDAK LULUS";

            hasil.setText(
                "================================\n"
                + "       DATA NILAI MAHASISWA\n"
                + "================================\n"
                + "Nama Mahasiswa : " + nama + "\n"
                + "NIM Mahasiswa  : " + nim + "\n"
                + "Program Studi  : " + prodi + "\n"
                + "--------------------------------\n"
                + "Nilai Tugas    : " + tugas + "\n"
                + "Nilai UTS      : " + uts + "\n"
                + "Nilai UAS      : " + uas + "\n"
                + "--------------------------------\n"
                + "Rata-rata      : " + String.format("%.2f", rata) + "\n"
                + "Grade          : " + grade + "\n"
                + "Status         : " + status + "\n"
                + "================================"
            );

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                this, "Input nilai harus berupa angka!"
            );
        }
    }//GEN-LAST:event_tombolSimpanActionPerformed

