    private void tampilkanDataKeTabel() {

    // Mengambil model dari JTable
    DefaultTableModel model =
            (DefaultTableModel) tabelMahasiswa.getModel();

    // Mengosongkan isi tabel sebelumnya
    model.setRowCount(0);

    // Mengambil data dari ArrayList
    for (dataMahasiswa m : mahasiswa) {

        model.addRow(new Object[]{
            m.getnimMahasiswa(),
            m.getnamaMahasiswa(),
            m.getprodi(),
            m.getjenisKelamin()
        });
    }
}
    
    private void tombolTampilkanActionPerformed(java.awt.event.ActionEvent evt) {                                                
        // TODO add your handling code here:
         tampilkanDataKeTabel();

    if (mahasiswa.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Belum ada data mahasiswa!");
    }
    }                                               

