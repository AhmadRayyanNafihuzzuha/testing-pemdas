    private void tombolCariActionPerformed(java.awt.event.ActionEvent evt) {                                           
        // TODO add your handling code here:
        String nimDicari = cariHapus.getText().trim();
        
        if (nimDicari.isEmpty()) {
            JOptionPane.showMessageDialog(this,"Masukkan NIM yang ingin dicari!");
            return;
        }
        boolean ditemukan = false;
        
        for (dataMahasiswa m: mahasiswa) {
            if (m.getnimMahasiswa().equals(nimDicari)) {
                hasil.setText(
                "DATA MAHASISWA DITEMUKAN! \n"
                        + "\nNAMA: " + m.getnamaMahasiswa()
                        + "\nNIM: " + m.getnimMahasiswa()
                        + "\nProdi: " + m.getprodi()
                        + "\nJenis Kelamin: " + m.getjenisKelamin());
                ditemukan = true;
                break;
            }
        }
        if (!ditemukan){
            hasil.setText("Data Mahasiswa dengan NIM" + nimDicari + ", Tidak ditemukan!");
        }
    }                                          

    private void hapusMahasiswaActionPerformed(java.awt.event.ActionEvent evt) {                                               
        // TODO add your handling code here:
        String nimDihapus = cariHapus.getText().trim();

        if (nimDihapus.isEmpty()) {
            JOptionPane.showMessageDialog(this,
            "Masukkan NIM yang ingin dihapus!");
            return;
        }

        boolean ditemukan = false;

        for (int i = 0; i < mahasiswa.size(); i++) {
            dataMahasiswa m = mahasiswa.get(i);
            if (m.getnimMahasiswa().equals(nimDihapus)) {
                mahasiswa.remove(i);
                tampilkanDataKeTabel();
                
                JOptionPane.showMessageDialog(this,"Data mahasiswa berhasil dihapus!");
                
                hasil.setText("Mahasiswa dengan NIM "
                        + nimDihapus + " berhasil dihapus.");
                
                ditemukan = true;
                break;
            }
        }
        
        if (!ditemukan) {
            JOptionPane.showMessageDialog(this,"Data mahasiswa tidak ditemukan!");
        }
    }                                              

