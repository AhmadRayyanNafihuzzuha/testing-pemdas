    private void tombolSimpanActionPerformed(java.awt.event.ActionEvent evt) {                                             
        // TODO add your handling code here:

        String nim = nimMahasiswa.getText().trim();
        String nama = namaMahasiswa.getText().trim();
        
        if (nim.isEmpty() || nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama dan NIM Wajib diisi!");
            return;
        }
        
        for (dataMahasiswa m : mahasiswa) {
             if (m.getnimMahasiswa().equals(nim)) {
                 JOptionPane.showMessageDialog(this,"NIM sudah terdaftar!");
                 return;
    }
}
        String prodi = String.valueOf(prodiBox.getSelectedItem());
        
        String jenisKelamin;
        if (rdoLaki.isSelected()) {
            jenisKelamin = "Laki - Laki";
        } else if (rdoCewek.isSelected()) {
            jenisKelamin = "Perempuan";
        } else {
            JOptionPane.showMessageDialog(this,"Pilih jenis kelamin!");
            return;
        }
        
        dataMahasiswa mahasiswaBaru = new dataMahasiswa(
        nim, nama, prodi, jenisKelamin);
        
        mahasiswa.add(mahasiswaBaru);
        tampilkanDataKeTabel();

        JOptionPane.showMessageDialog(this,"Data berhasil disimpan!.\n" + "Total Mahasiswa: " + mahasiswa.size());
    }                                            

