    private void tombolSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombolSimpanActionPerformed
        // TODO add your handling code here:

        String nim = nimMahasiswa.getText().trim();
        String nama = namaMahasiswa.getText().trim();

        if (nim.isEmpty() || nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama dan NIM Wajib diisi!");
            return;
        }
        
        String prodi = String.valueOf(prodiBox.getSelectedItem());

        String jenisKelamin;
        if (rdoLaki.isSelected()) {
            jenisKelamin = "Laki - Laki";
        } else if (rdoCewek.isSelected()) {
            jenisKelamin = "Perempuan";
        } else {
            JOptionPane.showMessageDialog(this,"Pilih jenis kelamin!");
            return;
        }
        
        mahasiswa = "NIM: " + nim
                + "\nNama: " + nama
                + "\nProgram Studi: " + prodi
                + "\nJenis Kelamin: " + jenisKelamin;
        JOptionPane.showMessageDialog(this, "Data berhasil disimpan sementara.");
    }//GEN-LAST:event_tombolSimpanActionPerformed

