    private void tombolCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombolCariActionPerformed
        // TODO add your handling code here:
        String nimDicari = cariHapus.getText().trim();

        if (nimDicari.isEmpty()) {
            JOptionPane.showMessageDialog(this,"Masukkan NIM yang ingin dicari!");
            return;
        }

        DefaultTableModel model =
        (DefaultTableModel) tabelMahasiswa.getModel();

        model.setRowCount(0);

        boolean ditemukan = false;

        for (dataMahasiswa m: mahasiswa) {
            if (m.getnimMahasiswa().equals(nimDicari)) {
                model.addRow(new Object[]{
                    m.getnimMahasiswa(),
                    m.getnamaMahasiswa(),
                    m.getprodi(),
                    m.getjenisKelamin()});

            ditemukan = true;
            break;
        }
        }
        if (!ditemukan){
            JOptionPane.showMessageDialog(this, "Data Mahasiswa Tidak Ditemukan!");
            tampilkanDataKeTabel();
        }
    }//GEN-LAST:event_tombolCariActionPerformed

    private void hapusMahasiswaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_hapusMahasiswaActionPerformed
        // TODO add your handling code here:
        int barisDipilih = tabelMahasiswa.getSelectedRow();

        if (barisDipilih == -1) {
            JOptionPane.showMessageDialog(this, "PIlih mahasiswa yang ingin dihapus!");
            return;
        }

        DefaultTableModel model =
        (DefaultTableModel) tabelMahasiswa.getModel();

        String nimDihapus = model.getValueAt(barisDipilih, 0).toString();

        for (int i = 0; i < mahasiswa.size(); i++) {
            dataMahasiswa m = mahasiswa.get(i);
            if (m.getnimMahasiswa().equals(nimDihapus)) {
                mahasiswa.remove(i);
                simpanDataKeFile();
                tampilkanDataKeTabel();

                JOptionPane.showMessageDialog(this,"Data mahasiswa berhasil dihapus!");

                hasil.setText("Mahasiswa dengan NIM "
                    + nimDihapus + " berhasil dihapus.");
                return;
            }
        }
    }//GEN-LAST:event_hapusMahasiswaActionPerformed

