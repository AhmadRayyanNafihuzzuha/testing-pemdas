    private void simpanDataKeFile() {
        try {
            FileWriter writer = new FileWriter("dataMahasiswa.txt");
            
            for (dataMahasiswa m : mahasiswa) {
                writer.write(
                        m.getnimMahasiswa() + ","
                                + m.getnamaMahasiswa() + ","
                                + m.getprodi() + ","
                                + m.getjenisKelamin() + "\n");
        }
            writer.close();
            System.out.println("Data berhasil disimpan ke file!");
        }
        catch (IOException e) {JOptionPane.showMessageDialog(this,
                "Gagal menyimpan data: " + e.getMessage());
        }
    }
    
    private void bacaDataDariFile() {
        
        java.io.File file = new java.io.File("dataMahasiswa.txt");
       
        if (!file.exists()) {
            return;
        }
        
        try {BufferedReader reader = new BufferedReader(new FileReader(file));
        
        String baris;
        
        mahasiswa.clear();
        
        while ((baris = reader.readLine()) != null) {
            String[] bagian = baris.split(",", -1);
            
            if (bagian.length == 4) {
                
                dataMahasiswa m = new dataMahasiswa(
                        bagian[0],
                        bagian[1],
                        bagian[2],
                        bagian[3]);
                
                mahasiswa.add(m);
            }
        }
        
        reader.close();
        
        System.out.println("Data berhasil dimuat!");
        
        }
        catch (IOException e) {JOptionPane.showMessageDialog(this,
                "Gagal membaca data: " + e.getMessage());
    }
}
